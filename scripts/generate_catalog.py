#!/usr/bin/env python3
"""Regenerate docs/CATALOG.md from the SKILL.md frontmatter of every skill in skills/.

Usage: python3 scripts/generate_catalog.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "skills"


def parse_frontmatter(text):
    m = re.match(r"---\s*\n(.*?)\n---\s*(\n|$)", text, re.S)
    if not m:
        return {}
    data, key = {}, None
    for line in m.group(1).splitlines():
        top = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if top:
            key, val = top.group(1), top.group(2).strip()
            if val in (">", "|", ">-", "|-"):
                val = ""
            data[key] = val.strip("\"'")
        elif key and line.startswith((" ", "\t")) and line.strip() and key in ("description", "name"):
            data[key] = (data[key] + " " + line.strip()).strip()
    return data


def collect():
    rows = []
    for d in sorted(SKILLS.iterdir(), key=lambda p: p.name.lower()):
        f = d / "SKILL.md"
        if not f.is_file():
            continue
        fm = parse_frontmatter(f.read_text(encoding="utf-8", errors="replace"))
        desc = re.sub(r"\s+", " ", fm.get("description", "")).strip().replace("|", "\\|")
        if len(desc) > 220:
            desc = desc[:217].rstrip() + "..."
        rows.append((d.name, fm.get("name", d.name), desc))
    return rows


def main():
    rows = collect()
    out = [
        "# Full skill catalog",
        "",
        f"All {len(rows)} skills in [`skills/`](../skills), generated by "
        "`python3 scripts/generate_catalog.py`. Do not edit by hand.",
        "",
        "| Folder | Display name | What it does |",
        "|---|---|---|",
    ]
    for folder, name, desc in rows:
        out.append(f"| [`{folder}`](../skills/{folder}/SKILL.md) | {name} | {desc} |")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "CATALOG.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote docs/CATALOG.md with {len(rows)} skills")


if __name__ == "__main__":
    sys.exit(main())
